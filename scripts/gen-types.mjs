import { readdirSync, writeFileSync, mkdirSync, readFileSync } from "node:fs"
import { join, dirname } from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, "..")
const RAW = join(ROOT, "mocks", "shared", "data", "raw")
const RESEARCH = join(ROOT, "mocks", "shared", "data", "research")
const OUT = join(ROOT, "generated", "api-types.d.ts")

function pascal(name) {
  return name
    .replace(/\.json$/, "")
    .replace(/[^a-zA-Z0-9]+/g, "_")
    .split("_")
    .filter(Boolean)
    .map((s) => s[0].toUpperCase() + s.slice(1))
    .join("")
}

function tsType(value, depth) {
  if (value === null || value === undefined) return "unknown"
  const t = typeof value
  if (t === "number") return "number"
  if (t === "string") return "string"
  if (t === "boolean") return "boolean"
  if (t === "bigint") return "number"
  if (Array.isArray(value)) {
    if (value.length === 0) return "unknown[]"
    const inner = value.map((v) => tsType(v, depth + 1))
    return `(${[...new Set(inner)].join(" | ")})[]`
  }
  if (t === "object") {
    if (depth > 6) return "Record<string, unknown>"
    const fields = Object.entries(value).map(([k, v]) => {
      const name = /^[a-zA-Z_$][a-zA-Z0-9_$]*$/.test(k) ? k : JSON.stringify(k)
      return `    ${name}: ${tsType(v, depth + 1)}`
    })
    return `{\n${fields.join("\n")}\n  }`
  }
  return "unknown"
}

function buildFile(relPath, absPath, name) {
  const data = JSON.parse(readFileSync(absPath, "utf8"))
  return `// from ${relPath}\nexport interface ${pascal(name)} ${tsType(data, 0).replace(/\n  }$/, "\n}")}\n`
}

function main() {
  const raw = readdirSync(RAW).filter((f) => f.endsWith(".json"))
  const research = readdirSync(RESEARCH).filter((f) => f.endsWith(".json"))
  const chunks = [
    "// Generated by scripts/gen-types.mjs — do not edit.\n",
    "// Types are inferred from real responses captured from app.example-service.ai on 2026-08-11\n",
    "// plus synthesized research data produced by scripts/regen-seed.mjs.\n",
  ]
  for (const f of raw.sort()) {
    chunks.push(buildFile(`mocks/shared/data/raw/${f}`, join(RAW, f), f))
  }
  for (const f of research.sort()) {
    chunks.push(buildFile(`mocks/shared/data/research/${f}`, join(RESEARCH, f), f))
  }
  mkdirSync(dirname(OUT), { recursive: true })
  writeFileSync(OUT, chunks.join("\n"))
  console.log(`Wrote ${OUT} (${raw.length} raw + ${research.length} research types)`)
}

main()
